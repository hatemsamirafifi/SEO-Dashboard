// oxlint-disable typescript-eslint/no-extraneous-class
import { and, desc, eq } from "drizzle-orm";
import { randomUUID } from "node:crypto";
import { db } from "@/db";
import {
  seoActionPlans,
  seoActionItems,
  seoActionEvidence,
  seoActionEvents,
} from "@/db/schema";
import type {
  SeoActionStatus,
  SeoVerificationOutcome,
} from "@/shared/samSeoAnalyst";

function genId(prefix: string): string {
  return `${prefix}_${randomUUID().replace(/-/g, "").slice(0, 12)}`;
}

export interface CreateActionPlanInput {
  id?: string;
  organizationId: string;
  projectId: string;
  title: string;
  description?: string | null;
  createdBy?: string | null;
}

export interface SaveActionItemInput {
  id?: string;
  actionPlanId?: string;
  organizationId: string;
  projectId: string;
  recommendationFingerprint: string;
  title: string;
  description?: string | null;
  category: string;
  priority: string;
  effort?: string | null;
  expectedImpact?: string | null;
  evidenceConfidence?: string | null;
  targetKeyword?: string | null;
  targetUrl?: string | null;
  recommendedAction: string;
  validationMetric: string;
  baselineValue?: string | null;
  baselineObservationDate?: string | null;
  dueDate?: string | null;
  status?: SeoActionStatus;
  evidence?: Array<{
    source: string;
    provider: string;
    sourceRecordId?: string | null;
    metricName: string;
    metricValue: string | number | boolean | null;
    observationDate?: string | null;
    observationRange?: string | null;
    targetDevice?: string | null;
    targetCountry?: string | null;
    targetUrl?: string | null;
    metadata?: Record<string, unknown> | null;
  }>;
  actor?: string;
  notes?: string | null;
}

export class SeoActionRepository {
  // ---------------------------------------------------------------------------
  // Plans
  // ---------------------------------------------------------------------------

  static async getPlansForProject(projectId: string, organizationId: string) {
    return db
      .select()
      .from(seoActionPlans)
      .where(
        and(
          eq(seoActionPlans.projectId, projectId),
          eq(seoActionPlans.organizationId, organizationId),
        ),
      )
      .orderBy(desc(seoActionPlans.createdAt));
  }

  static async getPlanById(
    planId: string,
    projectId: string,
    organizationId: string,
  ) {
    const rows = await db
      .select()
      .from(seoActionPlans)
      .where(
        and(
          eq(seoActionPlans.id, planId),
          eq(seoActionPlans.projectId, projectId),
          eq(seoActionPlans.organizationId, organizationId),
        ),
      )
      .limit(1);
    return rows.at(0) ?? null;
  }

  static async createPlan(input: CreateActionPlanInput) {
    const id = input.id ?? genId("plan");
    const now = new Date().toISOString();
    const [created] = await db
      .insert(seoActionPlans)
      .values({
        id,
        organizationId: input.organizationId,
        projectId: input.projectId,
        title: input.title,
        description: input.description ?? null,
        status: "active",
        createdBy: input.createdBy ?? null,
        createdAt: now,
        updatedAt: now,
      })
      .returning();
    return created;
  }

  static async getOrCreateDefaultPlan(
    projectId: string,
    organizationId: string,
    createdBy?: string | null,
  ) {
    const existing = await this.getPlansForProject(projectId, organizationId);
    if (existing.length > 0) {
      return existing[0];
    }
    return this.createPlan({
      organizationId,
      projectId,
      title: "Primary Action Plan",
      description: "Default action plan generated by SAM SEO Analyst",
      createdBy,
    });
  }

  // ---------------------------------------------------------------------------
  // Items
  // ---------------------------------------------------------------------------

  static async getItemsForPlan(
    planId: string,
    projectId: string,
    organizationId: string,
  ) {
    return db
      .select()
      .from(seoActionItems)
      .where(
        and(
          eq(seoActionItems.actionPlanId, planId),
          eq(seoActionItems.projectId, projectId),
          eq(seoActionItems.organizationId, organizationId),
        ),
      )
      .orderBy(desc(seoActionItems.createdAt));
  }

  static async getItemsForProject(
    projectId: string,
    organizationId: string,
    filter?: {
      status?: SeoActionStatus;
      category?: string;
      priority?: string;
    },
  ) {
    const conditions = [
      eq(seoActionItems.projectId, projectId),
      eq(seoActionItems.organizationId, organizationId),
    ];

    if (filter?.status) {
      conditions.push(eq(seoActionItems.status, filter.status));
    }
    if (filter?.category) {
      conditions.push(eq(seoActionItems.category, filter.category));
    }
    if (filter?.priority) {
      conditions.push(eq(seoActionItems.priority, filter.priority));
    }

    return db
      .select()
      .from(seoActionItems)
      .where(and(...conditions))
      .orderBy(desc(seoActionItems.createdAt));
  }

  static async getItemById(
    itemId: string,
    projectId: string,
    organizationId: string,
  ) {
    const rows = await db
      .select()
      .from(seoActionItems)
      .where(
        and(
          eq(seoActionItems.id, itemId),
          eq(seoActionItems.projectId, projectId),
          eq(seoActionItems.organizationId, organizationId),
        ),
      )
      .limit(1);
    return rows.at(0) ?? null;
  }

  static async getItemByFingerprint(
    fingerprint: string,
    projectId: string,
    organizationId: string,
  ) {
    const rows = await db
      .select()
      .from(seoActionItems)
      .where(
        and(
          eq(seoActionItems.recommendationFingerprint, fingerprint),
          eq(seoActionItems.projectId, projectId),
          eq(seoActionItems.organizationId, organizationId),
        ),
      )
      .limit(1);
    return rows.at(0) ?? null;
  }

  /**
   * Idempotently saves a recommendation as an action item.
   * If an item with the same recommendationFingerprint exists for this project,
   * returns the existing item instead of creating a duplicate.
   */
  static async saveActionItem(input: SaveActionItemInput) {
    const existing = await this.getItemByFingerprint(
      input.recommendationFingerprint,
      input.projectId,
      input.organizationId,
    );
    if (existing) {
      return { item: existing, isNew: false };
    }

    let planId = input.actionPlanId;
    if (!planId) {
      const defaultPlan = await this.getOrCreateDefaultPlan(
        input.projectId,
        input.organizationId,
        input.actor,
      );
      planId = defaultPlan.id;
    }

    const itemId = input.id ?? genId("item");
    const now = new Date().toISOString();
    const initialStatus = input.status ?? "proposed";

    const [item] = await db
      .insert(seoActionItems)
      .values({
        id: itemId,
        actionPlanId: planId,
        organizationId: input.organizationId,
        projectId: input.projectId,
        recommendationFingerprint: input.recommendationFingerprint,
        title: input.title,
        description: input.description ?? null,
        category: input.category,
        priority: input.priority,
        effort: input.effort ?? null,
        expectedImpact: input.expectedImpact ?? null,
        evidenceConfidence: input.evidenceConfidence ?? null,
        targetKeyword: input.targetKeyword ?? null,
        targetUrl: input.targetUrl ?? null,
        recommendedAction: input.recommendedAction,
        validationMetric: input.validationMetric,
        baselineValue: input.baselineValue ?? null,
        baselineObservationDate: input.baselineObservationDate ?? null,
        dueDate: input.dueDate ?? null,
        status: initialStatus,
        verificationOutcome: null,
        verificationNotes: null,
        createdAt: now,
        updatedAt: now,
        completedAt: null,
        verifiedAt: null,
      })
      .returning();

    // Attach supporting evidence rows
    if (input.evidence && input.evidence.length > 0) {
      const evidenceRows = input.evidence.map((ev) => ({
        id: genId("ev"),
        actionItemId: itemId,
        source: ev.source,
        provider: ev.provider,
        sourceRecordId: ev.sourceRecordId ?? null,
        metricName: ev.metricName,
        metricValue: ev.metricValue != null ? String(ev.metricValue) : "",
        observationDate: ev.observationDate ?? null,
        observationRange: ev.observationRange ?? null,
        targetDevice: ev.targetDevice ?? null,
        targetCountry: ev.targetCountry ?? null,
        targetUrl: ev.targetUrl ?? null,
        metadata: ev.metadata ? JSON.stringify(ev.metadata) : null,
      }));
      await db.insert(seoActionEvidence).values(evidenceRows);
    }

    // Append initial creation event
    await db.insert(seoActionEvents).values({
      id: genId("evt"),
      actionItemId: itemId,
      actor: input.actor ?? "user",
      previousStatus: null,
      newStatus: initialStatus,
      notes: input.notes ?? "Created from SEO recommendation",
      metadata: null,
      createdAt: now,
    });

    return { item, isNew: true };
  }

  static async updateItem(
    itemId: string,
    projectId: string,
    organizationId: string,
    updates: Partial<{
      status: SeoActionStatus;
      verificationOutcome: SeoVerificationOutcome | null;
      verificationNotes: string | null;
      dueDate: string | null;
      completedAt: string | null;
      verifiedAt: string | null;
      description: string | null;
    }>,
  ) {
    const now = new Date().toISOString();
    const [updated] = await db
      .update(seoActionItems)
      .set({
        ...updates,
        updatedAt: now,
      })
      .where(
        and(
          eq(seoActionItems.id, itemId),
          eq(seoActionItems.projectId, projectId),
          eq(seoActionItems.organizationId, organizationId),
        ),
      )
      .returning();
    return updated ?? null;
  }

  // ---------------------------------------------------------------------------
  // Evidence & Events
  // ---------------------------------------------------------------------------

  static async getEvidenceForItem(actionItemId: string) {
    return db
      .select()
      .from(seoActionEvidence)
      .where(eq(seoActionEvidence.actionItemId, actionItemId));
  }

  static async addEvent(event: {
    actionItemId: string;
    actor: string;
    previousStatus?: string | null;
    newStatus: string;
    notes?: string | null;
    metadata?: Record<string, unknown> | null;
  }) {
    const id = genId("evt");
    const now = new Date().toISOString();
    const [created] = await db
      .insert(seoActionEvents)
      .values({
        id,
        actionItemId: event.actionItemId,
        actor: event.actor,
        previousStatus: event.previousStatus ?? null,
        newStatus: event.newStatus,
        notes: event.notes ?? null,
        metadata: event.metadata ? JSON.stringify(event.metadata) : null,
        createdAt: now,
      })
      .returning();
    return created;
  }

  static async getEventsForItem(actionItemId: string) {
    return db
      .select()
      .from(seoActionEvents)
      .where(eq(seoActionEvents.actionItemId, actionItemId))
      .orderBy(desc(seoActionEvents.createdAt));
  }
}
